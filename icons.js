window.getProductIcon = function (p) {
  var name = (p && p.name) || "";
  var rules = window.PRODUCT_ICON_RULES;
  for (var i = 0; i < rules.length; i++) {
    if (name.indexOf(rules[i][0]) !== -1) return rules[i][1];
  }
  var byDept = { "精肉": "🍖", "水産": "🐟", "青果": "🥬", "デリカ": "🍱", "ベーカリー": "🍞", "加食": "🛒", "洋日配": "🥛", "和日配": "🍱", "とうふ屋上野": "🍱", "菓子": "🍬" };
  return byDept[p && p.department] || "🛒";
};
window.getRecipeIcon = function (name) {
  return (window.RECIPE_ICONS && window.RECIPE_ICONS[name]) || "🍽️";
};
window.getDeptColor = function (dept) {
  return (window.DEPT_COLORS && window.DEPT_COLORS[dept]) || "#eef0ee";
};
